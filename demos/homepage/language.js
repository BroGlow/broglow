  const query = new URLSearchParams(location.search).get('lang');
  let language = supported(query) ? query : supported(saved) ? saved : 'en';
  function t(key, variables = {}) {
    const value = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (match, name) => variables[name] ?? match);
  }
  function render() {
    document.documentElement.lang = language;
    for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
    for (const attribute of ['aria-label', 'alt', 'title', 'content']) {
      for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
        node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
      }
    }
    for (const link of document.querySelectorAll('[data-guide-link]')) {
      const url = new URL(link.href);
      url.pathname = url.pathname.replace(/\/docs\/(?:ru\/)?/, `/docs/${language === 'ru' ? 'ru/' : ''}`);
      url.searchParams.set('lang', language);
      link.href = url.href;
    }
    const picker = document.querySelector('#language');
    if (picker) picker.value = language;
    window.dispatchEvent(new CustomEvent('broglow:language', {detail: {language}}));
  }
  function setLanguage(value) {
    if (!supported(value)) return;
    language = value;
    try { localStorage.setItem('broglow-language', language); } catch {}
    const url = new URL(location.href);
    url.searchParams.set('lang', language);
    history.replaceState(null, '', url);
    render();
  }

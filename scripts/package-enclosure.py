#!/usr/bin/env python3
"""Generate, validate and package the enclosure from an isolated copy of CAD source."""

import argparse
import importlib.metadata
import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MODEL = Path("models/clawlight")
CAD_FILES = (
    "clawlight.py",
    "hand_joint.py",
    "appearance.py",
    "exploded.py",
    "usb_coupon.py",
    "check.py",
    "dimensions.py",
    "package_prints.py",
    "requirements.txt",
    "PRINT_GUIDE.en.md",
    "PRINT_GUIDE.md",
    "slicer-validation.json",
)


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


release = load("package_macos", ROOT / "scripts/package-macos.py")
prints = load("package_prints", ROOT / MODEL / "package_prints.py")


def source_files():
    """Only build inputs and documented references; never copy old exports or private files."""
    files = {
        Path("LICENSE"),
        *(Path(name) for name in prints.REFERENCE_FILES),
        *(MODEL / name for name in CAD_FILES),
    }
    for path in files:
        source = ROOT / path
        release.require(
            source.is_file()
            and not source.is_symlink()
            and source.resolve().is_relative_to(ROOT),
            f"Missing or unsafe source input: {path}",
        )
    return sorted(files)


def prepare_source(output, inputs):
    source = output / "source"
    release.require(
        not ROOT.is_relative_to(source),
        "Build output would replace the source checkout.",
    )
    marker = source / ".enclosure-build"
    if source.exists():
        release.require(
            marker.is_file(), f"Refusing to replace an unknown directory: {source}"
        )
        shutil.rmtree(source)
    source.mkdir(parents=True)
    marker.write_text(
        "Generated by scripts/package-enclosure.py; safe to regenerate.\n"
    )
    for name in inputs:
        target = source / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, target)
    (source / MODEL / "preview").mkdir(exist_ok=True)
    return source


def identity(version, tag):
    if (ROOT / ".git").exists():
        release.ROOT = ROOT
        return release.release_identity(version, tag)
    release.require(not tag, "--release-tag requires a Git checkout.")
    return None, None  # Source archives carry no verifiable Git identity.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "dist/enclosure")
    parser.add_argument(
        "--release-tag",
        help="Require a clean matching release tag before and after generation.",
    )
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="Only validate --release-tag; no CAD dependencies needed.",
    )
    args = parser.parse_args()
    version = re.search(
        r'^version = "([^"]+)"$', (ROOT / "Cargo.toml").read_text(), re.M
    ).group(1)
    commit, dirty = identity(version, args.release_tag)
    if args.check_only:
        release.require(args.release_tag, "--check-only requires --release-tag.")
        print(f"Release source verified: {args.release_tag} ({commit})")
        return
    toolchain = {}
    for requirement in (ROOT / MODEL / "requirements.txt").read_text().splitlines():
        if not requirement.strip() or requirement.startswith("#"):
            continue
        name, expected = requirement.split("==")
        actual = importlib.metadata.version(name)
        release.require(
            actual == expected,
            f"Install pinned CAD requirements: {name}=={expected}, found {actual}",
        )
        toolchain[name] = actual
    inputs = source_files()
    input_hashes = {path.as_posix(): release.sha256(ROOT / path) for path in inputs}
    output = args.output_dir.resolve()
    source = prepare_source(output, inputs)
    provenance = {
        "version": version,
        "source_commit": commit,
        "source_dirty": dirty,
        "release_tag": args.release_tag,
        "python": sys.version.split()[0],
        "dependencies": toolchain,
        "source_inputs_sha256": input_hashes,
        "slicer_evidence": "Reviewed slicer-validation.json reused only after exact generated STL hash matching; no new slicing performed.",
    }
    (source / "BUILD.json").write_text(json.dumps(provenance, indent=2) + "\n")
    model = source / MODEL

    def run(*args, cwd=source):
        subprocess.run([sys.executable, *map(str, args)], cwd=cwd, check=True)

    run(
        "-c",
        "import importlib; from build123d import export_step; import clawlight; "
        "clawlight.export_all(); "
        "[export_step(importlib.import_module(name).gen_step(), name+'.step') "
        "for name in ('appearance', 'exploded', 'usb_coupon')]",
        cwd=model,
    )
    run(model / "check.py")
    run(model / "dimensions.py")
    run(model / "package_prints.py", "--output-dir", output)
    run(model / "package_prints.py", "--output-dir", output, "--check")
    release.require(
        input_hashes
        == {path.as_posix(): release.sha256(ROOT / path) for path in inputs},
        "Source inputs changed during generation; rerun from a stable checkout.",
    )
    release.require(
        identity(version, args.release_tag) == (commit, dirty),
        "Source identity changed during generation; rerun from a stable checkout.",
    )
    archive = output / f"clawlight-enclosure-v{version}.zip"
    shutil.copy2(output / "clawlight-print-pack.zip", archive)
    checksum = archive.with_name(archive.name + ".sha256")
    checksum.write_text(f"{release.sha256(archive)}  {archive.name}\n")
    print(
        f"Generated and verified: {archive}\nChecksum: {checksum}\nCAD and reports: {model}"
    )


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate, validate and package the enclosure from an isolated copy of CAD source."""

import argparse
import importlib.metadata
import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parents[1]
MODEL = Path("models/broglow")
MAGNETIC = Path("models/magnetic")
# Only build inputs and documented references; never copy old exports or private files.
SOURCE_FILES = (
    Path("LICENSE"),
    Path("Cargo.toml"),
    Path("scripts/package-enclosure.py"),
    Path("scripts/package-macos.py"),
    *(
        MODEL / name
        for name in (
            "broglow.py",
            "hand_joint.py",
            "check.py",
            "usb_coupon.py",
            "requirements.txt",
        )
    ),
    *(
        MAGNETIC / name
        for name in (
            "magnetic.py",
            "refined.py",
            "round3x2.py",
            "round3x2_exploded.py",
            "appearance.py",
            "exploded.py",
            "GUIDE_ROUND3X2.en.md",
            "GUIDE_ROUND3X2.md",
            "slicer-validation.json",
        )
    ),
)
PARTS = (
    "01_mascot_magnetic_orange",
    "02_eye_black_x2",
    "03_tower_magnetic_black",
    "04_rear_cover_black",
    "05_LED_retainer_black",
)


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


release = load("package_macos", ROOT / "scripts/package-macos.py")


def source_files():
    files = set(SOURCE_FILES)
    for path in files:
        source = ROOT / path
        release.require(
            source.is_file()
            and not source.is_symlink()
            and source.resolve().is_relative_to(ROOT),
            f"Missing or unsafe source input: {path}",
        )
    return sorted(files)


def prepare_source(output, inputs):
    source = output / "source"
    release.require(
        not ROOT.is_relative_to(source),
        "Build output would replace the source checkout.",
    )
    marker = source / ".enclosure-build"
    if source.exists():
        release.require(
            marker.is_file(), f"Refusing to replace an unknown directory: {source}"
        )
        shutil.rmtree(source)
    source.mkdir(parents=True)
    marker.write_text(
        "Generated by scripts/package-enclosure.py; safe to regenerate.\n"
    )
    for name in inputs:
        target = source / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, target)
        if target.suffix == ".md":
            release.resolve_repo_url(target)
    (source / MODEL / "preview").mkdir(exist_ok=True)
    return source


def identity(version, tag):
    if (ROOT / ".git").exists():
        release.ROOT = ROOT
        return release.release_identity(version, tag)
    release.require(not tag, "--release-tag requires a Git checkout.")
    return None, None  # Source archives carry no verifiable Git identity.


def package_magnetic(source, output, version):
    """Package the five production parts and assembly views in one flat folder."""
    model = source / MAGNETIC
    slices = json.loads((model / "slicer-validation.json").read_text())
    report = json.loads((model / "validation.json").read_text())
    release.require(report["status"] == "passed", "Magnetic validation failed")
    names = [part["file"] for part in slices["parts"]]
    expected = [f"stl/{name}.stl" for name in PARTS]
    release.require(sorted(names) == sorted(expected), "Wrong magnetic print inventory")
    for part in slices["parts"]:
        release.require(
            release.sha256(model / part["file"]) == part["sha256"],
            f"Stale magnetic slicer evidence: {part['file']}",
        )
    generated = [Path("stl") / f"{name}.stl" for name in PARTS]
    generated += [Path("step") / f"{name}.step" for name in PARTS]
    generated += [Path(name) for name in ("round3x2.step", "round3x2_exploded.step")]
    entries = {path.name: (model / path).read_bytes() for path in generated}
    entries["BUILD.json"] = (source / "BUILD.json").read_bytes()
    archive = output / f"broglow-enclosure-magnetic-v{version}.zip"
    with ZipFile(archive, "w", ZIP_DEFLATED) as zipped:
        for name, data in sorted(entries.items()):
            zipped.writestr(name, data)
    with ZipFile(archive) as zipped:
        release.require(zipped.testzip() is None, "Corrupt magnetic archive")
    return archive


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "dist/enclosure")
    parser.add_argument(
        "--release-tag",
        help="Require a clean matching release tag before and after generation.",
    )
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="Only validate --release-tag; no CAD dependencies needed.",
    )
    args = parser.parse_args()
    version = re.search(
        r'^version = "([^"]+)"$', (ROOT / "Cargo.toml").read_text(), re.M
    ).group(1)
    commit, dirty = identity(version, args.release_tag)
    if args.check_only:
        release.require(args.release_tag, "--check-only requires --release-tag.")
        print(f"Release source verified: {args.release_tag} ({commit})")
        return
    toolchain = {}
    for requirement in (ROOT / MODEL / "requirements.txt").read_text().splitlines():
        if not requirement.strip() or requirement.startswith("#"):
            continue
        name, expected = requirement.split("==")
        actual = importlib.metadata.version(name)
        release.require(
            actual == expected,
            f"Install pinned CAD requirements: {name}=={expected}, found {actual}",
        )
        toolchain[name] = actual
    inputs = source_files()
    input_hashes = {path.as_posix(): release.sha256(ROOT / path) for path in inputs}
    output = args.output_dir.resolve()
    source = prepare_source(output / "magnetic-build", inputs)
    provenance = {
        "version": version,
        "variant": "magnetic",
        "source_commit": commit,
        "source_dirty": dirty,
        "release_tag": args.release_tag,
        "python": sys.version.split()[0],
        "dependencies": toolchain,
        "source_inputs_sha256": input_hashes,
        "slicer_evidence": "Reviewed slicer-validation.json reused only after exact generated STL hash matching; no new slicing performed.",
    }
    (source / "BUILD.json").write_text(json.dumps(provenance, indent=2) + "\n")
    model = source / MAGNETIC

    def run(*args, cwd=source):
        subprocess.run([sys.executable, *map(str, args)], cwd=cwd, check=True)

    run(model / "round3x2.py", "--output-dir", model)
    archive = package_magnetic(source, output, version)
    release.require(
        input_hashes
        == {path.as_posix(): release.sha256(ROOT / path) for path in inputs},
        "Source inputs changed during generation; rerun from a stable checkout.",
    )
    release.require(
        identity(version, args.release_tag) == (commit, dirty),
        "Source identity changed during generation; rerun from a stable checkout.",
    )
    checksum = archive.with_name(archive.name + ".sha256")
    checksum.write_text(f"{release.sha256(archive)}  {archive.name}\n")
    print(
        f"Generated and verified: {archive}\nChecksum: {checksum}\nCAD and reports: {model}"
    )


if __name__ == "__main__":
    main()
